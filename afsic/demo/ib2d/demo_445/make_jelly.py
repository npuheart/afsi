"""Python port of IB2d's ``Make_Jelly_Geometry.m`` (+ ``input2d`` writer).

    python make_jelly.py <out_dir> [Ny] [dt] [Tfinal] [print_dump]

Writes ``input2d``, ``jelly.vertex``, ``jelly.spring``, ``jelly.target`` and
``jelly.nonInv_beam`` for the Hoover-Jellyfish model (Battista's IB2d port of
Hoover & Miller 2015, "A numerical study of the benefits of driving jellyfish
bells at their natural frequency", J. Theor. Biol. 374) on an Nx x Ny grid with
Nx = Ny * Lx / Ly (square cells).

Model ingredients (identical to ``Make_Jelly_Geometry.m``):

* Lagrangian spacing ``ds = min(Lx/(2 Nx), Ly/(2 Ny))`` (= dx/2);
* the bell is the ellipse x = a cos t, y = b sin t with a = 0.5, b = 0.75,
  truncated at y = d = -0.25 (theta_lim = asin(d/b)), shifted to (1.5, 2.0);
  npts = 2*npts_wing - 1 points along the bell outline (apex first, then the
  left side, then the right side);
* springs: 2*npts_wing structural springs (the bell outline, stiffness
  kappa_spring = 1e7 written as kappa_spring/ds in the file -- the file value
  is what IB2d simulates) plus npts_musc = floor(npts_wing/4) *muscle* springs
  of stiffness F = 1e5 connecting the two arm tips; the muscles are written as
  the LAST rows of the .spring file (this order is depended upon by the muscle
  driver of ``run_reference.py`` and by main.py);
* non-invariant beams (stiffness kappa_beam = 2.5e5 written as
  kappa_beam/ds^3) along the bell outline; each beam stores the reference
  second difference (C1, C2) of its three points at t = 0;
* a line of ``flow blocker`` target points of stiffness k_Target = 2.5e6 at
  x = ds : 4 ds : Lx - ds, y = Ly - 4 ds, tethered to their initial positions.
"""
import os
import sys

import numpy as np

A_SEMI = 0.5          # bell semi-axis in x
B_SEMI = 0.75         # bell semi-axis in y
Y_LOW = -0.25         # lowest point along the bell
KAPPA_SPRING = 1e7    # spring constant (N)
KAPPA_BEAM = 2.5e5    # beam stiffness (N m^2)
F_MUSCLE = 1e5        # jellyfish contraction force
K_TARGET = 2.5e6      # target (blocker) stiffness

