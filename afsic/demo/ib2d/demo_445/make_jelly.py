def build(Ny, Lx=3.0, Ly=10.0, mu=6.667, rho=1000.0):
    """Return the vertex/spring/target/beam arrays for the Hoover jellyfish."""
    Nx = int(round(Ny * Lx / Ly))
    ds = min(Lx / (2 * Nx), Ly / (2 * Ny))

    # --- bell outline (apex first, then left side, then right side) ---------
    theta_lim = np.arcsin(Y_LOW / B_SEMI)
    theta = np.pi / 2
    xl, yl = [], []
    while theta < np.pi - theta_lim:
        xl.append(A_SEMI * np.cos(theta))
        yl.append(B_SEMI * np.sin(theta))
        theta += ds / np.sqrt((A_SEMI * np.sin(theta)) ** 2
                              + (B_SEMI * np.cos(theta)) ** 2)
    xl, yl = np.array(xl), np.array(yl)
    n_wing = len(xl) - 1
    npts = 2 * n_wing + 1
    x = np.concatenate([xl, -xl[1:]]) + 1.5
    y = np.concatenate([yl, yl[1:]]) + 2.0
    n_musc = n_wing // 4                       # floor(npts_wing/4)

    # --- flow blocker line along the top edge ------------------------------
    n_blk = int(np.floor((Lx - ds - ds) / (4 * ds))) + 1
    xb = ds + 4 * ds * np.arange(n_blk)
    yb = np.full(n_blk, Ly - 4 * ds)
    X = np.vstack([np.column_stack([x, y]), np.column_stack([xb, yb])])
    Nb = len(X)

    def dist(a, b):                            # 1-based indices, as in the .m
        return float(np.sqrt((X[a - 1, 0] - X[b - 1, 0]) ** 2
                             + (X[a - 1, 1] - X[b - 1, 1]) ** 2))

    # --- springs: left side, right side, then the muscles ------------------
    m1, m2, ks, L0 = [], [], [], []
    k_edge = KAPPA_SPRING / ds
    for s in range(1, n_wing + 1):             # left side: (s, s+1)
        m1.append(s); m2.append(s + 1); ks.append(k_edge); L0.append(dist(s, s + 1))
    for s in range(1, n_wing + 1):             # right side
        if s == 1:
            a, b = 1, n_wing + 2
        else:
            a, b = (s - 1) + (n_wing + 1), s + (n_wing + 1)
        m1.append(a); m2.append(b); ks.append(k_edge); L0.append(dist(a, b))
    ind_l = 1 + n_wing - n_musc + 1            # first muscle point on the left arm
    ind_r = 1 + 2 * n_wing - n_musc + 1        # first muscle point on the right arm
    for s in range(n_musc):                    # muscles between the arm tips
        a, b = ind_l + s, ind_r + s
        m1.append(a); m2.append(b); ks.append(F_MUSCLE); L0.append(dist(a, b))
    springs = dict(p1=np.array(m1, np.int64) - 1, p2=np.array(m2, np.int64) - 1,
                   k=np.array(ks), L0=np.array(L0), n_musc=n_musc, n_wing=n_wing)

    # --- non-invariant beams (reference second differences) ----------------
    b1, b2, b3, bk, C = [], [], [], [], []
    kb = KAPPA_BEAM / ds ** 3

    def beam(i1, i2, i3):
        b1.append(i1); b2.append(i2); b3.append(i3); bk.append(kb)
        C.append([X[i1 - 1, 0] + X[i3 - 1, 0] - 2 * X[i2 - 1, 0],
                  X[i1 - 1, 1] + X[i3 - 1, 1] - 2 * X[i2 - 1, 1]])

    beam(2, 1, n_wing + 2)                     # middle three points at the top
    for s in range(2, n_wing + 1):             # left side
        beam(s + 1, s, s - 1)
    for s in range(2, n_wing + 1):             # right side
        ss = s + n_wing
        if s == 2:
            beam(1, ss, ss + 1)
        else:
            beam(ss - 1, ss, ss + 1)
    beams = dict(p1=np.array(b1, np.int64) - 1, p2=np.array(b2, np.int64) - 1,
                 p3=np.array(b3, np.int64) - 1, kb=np.array(bk),
                 C=np.array(C))

    # --- blockers as target points -----------------------------------------
    tgt = dict(ids=np.arange(npts, Nb, dtype=np.int64), k=np.full(Nb - npts, K_TARGET))
    return dict(Nx=Nx, Ny=Ny, Lx=Lx, Ly=Ly, ds=ds, X=X, springs=springs,
                beams=beams, targets=tgt, npts=npts, n_wing=n_wing, n_musc=n_musc,
                mu=mu, rho=rho)


def write(out, Ny, dt, Tfinal, print_dump, Lx=3.0, Ly=10.0, mu=6.667, rho=1000.0):
    g = build(Ny, Lx, Ly, mu, rho)
    os.makedirs(out, exist_ok=True)
    Nx, ds, X = g["Nx"], g["ds"], g["X"]

    with open(os.path.join(out, "jelly.vertex"), "w") as fh:
        fh.write(f"{len(X)}\n")
        for xv, yv in X:
            fh.write(f"{xv:1.16e} {yv:1.16e}\n")

    sp = g["springs"]
    with open(os.path.join(out, "jelly.spring"), "w") as fh:
        fh.write(f"{len(sp['p1'])}\n")
        for a, b, k, L in zip(sp["p1"] + 1, sp["p2"] + 1, sp["k"], sp["L0"]):
            fh.write(f"{a} {b} {k:1.16e} {L:1.16e} 1\n")

    bm = g["beams"]
    with open(os.path.join(out, "jelly.nonInv_beam"), "w") as fh:
        fh.write(f"{len(bm['p1'])}\n")
        for a, b, c, k, C in zip(bm["p1"] + 1, bm["p2"] + 1, bm["p3"] + 1,
                                 bm["kb"], bm["C"]):
            fh.write(f"{a} {b} {c} {k:1.16e} {C[0]:1.16e} {C[1]:1.16e}\n")

    tg = g["targets"]
    with open(os.path.join(out, "jelly.target"), "w") as fh:
        fh.write(f"{len(tg['ids'])}\n")
        for i, k in zip(tg["ids"] + 1, tg["k"]):
            fh.write(f"{i} {k:1.16e}\n")

    with open(os.path.join(out, "input2d"), "w") as fh:
        fh.write(INPUT2D_TEMPLATE.format(
            Nx=Nx, Ny=Ny, Lx=f"{Lx:.1f}", Ly=f"{Ly:.1f}", mu=mu, rho=rho,
            dt=f"{dt:.1e}", Tfinal=f"{Tfinal:.1f}", print_dump=print_dump))

    print(f"wrote {out}: Nx={Nx} Ny={Ny} ds={ds:g} "
          f"bell={g['npts']} pts ({g['n_wing']} per side), "
          f"muscles={g['n_musc']}, springs={len(sp['p1'])}, "
          f"beams={len(bm['p1'])}, blockers={len(tg['ids'])}, "
          f"dt={dt:g}, Tfinal={Tfinal}, print_dump={print_dump}")
    return g


if __name__ == "__main__":
    args = sys.argv[1:]
    out = args[0]
    vals = list(args[1:]) + ["160", "4e-5", "1.0", "250"][len(args) - 1:]
    write(out, int(vals[0]), float(vals[1]), float(vals[2]), int(vals[3]))
